DROP DATABASE IF EXISTS liga;
CREATE DATABASE liga CHARACTER SET utf8mb4 COLLATE utf8mb4_spanish_ci;
USE liga;

CREATE TABLE equipo (
  id_equipo  INT PRIMARY KEY,
  nombre     VARCHAR(50) NOT NULL UNIQUE,
  ciudad     VARCHAR(50) NOT NULL,
  pabellon   VARCHAR(80)
);

CREATE TABLE jugador (
  id_jugador        INT PRIMARY KEY,
  nombre            VARCHAR(80) NOT NULL,
  posicion          VARCHAR(10) NOT NULL,
  dorsal            INT NOT NULL,
  fecha_nacimiento  DATE NOT NULL,
  id_equipo         INT NOT NULL,
  FOREIGN KEY (id_equipo) REFERENCES equipo (id_equipo),
  UNIQUE (id_equipo, dorsal)
);

CREATE TABLE partido (
  id_partido       INT PRIMARY KEY,
  jornada          INT NOT NULL,
  fecha            DATE NOT NULL,
  id_local         INT NOT NULL,
  id_visitante     INT NOT NULL,
  goles_local      INT NOT NULL,
  goles_visitante  INT NOT NULL,
  FOREIGN KEY (id_local) REFERENCES equipo (id_equipo),
  FOREIGN KEY (id_visitante) REFERENCES equipo (id_equipo)
);

CREATE TABLE gol (
  id_gol      INT PRIMARY KEY,
  id_partido  INT NOT NULL,
  id_jugador  INT NOT NULL,
  minuto      INT NOT NULL,
  FOREIGN KEY (id_partido) REFERENCES partido (id_partido),
  FOREIGN KEY (id_jugador) REFERENCES jugador (id_jugador)
);

